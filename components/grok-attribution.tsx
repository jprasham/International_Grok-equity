import { cn } from "@/lib/utils";

type GrokAttributionProps = {
  /** `working` = researching animation; `done` = calm credit; `inline` = compact strip */
  tone?: "inline" | "working" | "done";
  className?: string;
};

export function GrokAttribution({ tone = "inline", className }: GrokAttributionProps) {
  const working = tone === "working";
  const done = tone === "done";

  return (
    <div
      className={cn(
        "flex items-center gap-3",
        working && "rounded-lg border border-primary/25 bg-primary/6 px-3 py-2.5",
        done && "rounded-lg border border-border-soft bg-card px-3 py-2",
        className,
      )}
      role="note"
    >
      <span className="relative grid size-8 shrink-0 place-items-center" aria-hidden>
        {working && (
          <span className="absolute inset-0 rounded-full border border-dashed border-primary/50 motion-safe:animate-grok-orbit" />
        )}
        <span
          className={cn(
            "grid size-5 place-items-center rounded-full bg-primary font-mono text-[10px] font-bold text-primary-foreground",
            working && "motion-safe:animate-grok-breathe",
          )}
        >
          G
        </span>
      </span>

      <div className="min-w-0 leading-tight">
        <p className="font-mono text-[10px] tracking-[0.14em] text-muted-foreground uppercase">
          {working ? "Generating with" : done ? "Generated by" : "Research powered by"}
        </p>
        <p
          className={cn(
            "text-[15px] font-bold tracking-tight",
            working
              ? "grok-mark-text motion-safe:animate-grok-shimmer"
              : "text-foreground",
          )}
        >
          Grok
          {working && (
            <span className="ml-1.5 inline-flex gap-0.5 align-middle" aria-hidden>
              <span className="size-1 rounded-full bg-primary motion-safe:animate-pulse [animation-delay:0ms]" />
              <span className="size-1 rounded-full bg-primary motion-safe:animate-pulse [animation-delay:150ms]" />
              <span className="size-1 rounded-full bg-primary motion-safe:animate-pulse [animation-delay:300ms]" />
            </span>
          )}
        </p>
      </div>
    </div>
  );
}
